from enum import Enum
from pydantic import BaseModel, Field
from typing import Any, Dict
from datetime import datetime, timezone
import uuid

class LiveEventType(str, Enum):
    SESSION_CREATED = "SESSION_CREATED"
    SESSION_STARTED = "SESSION_STARTED"

    NAVIGATION_STARTED = "NAVIGATION_STARTED"
    NAVIGATION_COMPLETED = "NAVIGATION_COMPLETED"

    DOM_OBSERVED = "DOM_OBSERVED"

    ACTION_STARTED = "ACTION_STARTED"
    ACTION_COMPLETED = "ACTION_COMPLETED"
    ACTION_FAILED = "ACTION_FAILED"

    SCREENSHOT_CAPTURED = "SCREENSHOT_CAPTURED"

    CONSOLE_EVENT = "CONSOLE_EVENT"
    PAGE_ERROR = "PAGE_ERROR"

    NETWORK_REQUEST_STARTED = "NETWORK_REQUEST_STARTED"
    NETWORK_REQUEST_COMPLETED = "NETWORK_REQUEST_COMPLETED"
    NETWORK_REQUEST_FAILED = "NETWORK_REQUEST_FAILED"

    PERFORMANCE_UPDATE = "PERFORMANCE_UPDATE"

    ASSERTION_STARTED = "ASSERTION_STARTED"
    ASSERTION_PASSED = "ASSERTION_PASSED"
    ASSERTION_FAILED = "ASSERTION_FAILED"

    EVIDENCE_CAPTURED = "EVIDENCE_CAPTURED"

    DETERMINISTIC_EVALUATION_STARTED = "DETERMINISTIC_EVALUATION_STARTED"
    DETERMINISTIC_EVALUATION_COMPLETED = "DETERMINISTIC_EVALUATION_COMPLETED"

    DIAGNOSIS_STARTED = "DIAGNOSIS_STARTED"
    DIAGNOSIS_COMPLETED = "DIAGNOSIS_COMPLETED"

    REMEDIATION_PROPOSED = "REMEDIATION_PROPOSED"

    GOVERNANCE_REQUIRED = "GOVERNANCE_REQUIRED"

    STRATEGY_PLANNED = "STRATEGY_PLANNED"
    STRATEGY_ADAPTED = "STRATEGY_ADAPTED"

    RETEST_STARTED = "RETEST_STARTED"
    RETEST_COMPLETED = "RETEST_COMPLETED"

    # Slice 8E Memory Events
    MEMORY_RETRIEVAL_STARTED = "MEMORY_RETRIEVAL_STARTED"
    MEMORY_RETRIEVAL_COMPLETED = "MEMORY_RETRIEVAL_COMPLETED"
    MEMORY_CANDIDATE_CREATED = "MEMORY_CANDIDATE_CREATED"
    MEMORY_PROMOTED = "MEMORY_PROMOTED"
    MEMORY_INVALIDATED = "MEMORY_INVALIDATED"
    MEMORY_CONTRADICTION_DETECTED = "MEMORY_CONTRADICTION_DETECTED"

    # Slice 8K Change Impact & Adaptive Regression Events
    CHANGE_ANALYSIS_STARTED = "CHANGE_ANALYSIS_STARTED"
    CHANGE_ANALYSIS_COMPLETED = "CHANGE_ANALYSIS_COMPLETED"
    IMPACT_GRAPH_BUILT = "IMPACT_GRAPH_BUILT"
    REGRESSION_PLAN_CREATED = "REGRESSION_PLAN_CREATED"
    REGRESSION_SCOPE_EXPANDED = "REGRESSION_SCOPE_EXPANDED"
    REGRESSION_EXECUTION_STARTED = "REGRESSION_EXECUTION_STARTED"
    REGRESSION_EXECUTION_COMPLETED = "REGRESSION_EXECUTION_COMPLETED"
    BASELINE_COMPARISON_STARTED = "BASELINE_COMPARISON_STARTED"
    BASELINE_COMPARISON_COMPLETED = "BASELINE_COMPARISON_COMPLETED"
    REGRESSION_FINDING_DETECTED = "REGRESSION_FINDING_DETECTED"

    SESSION_COMPLETED = "SESSION_COMPLETED"
    SESSION_FAILED = "SESSION_FAILED"
    SESSION_CANCELLED = "SESSION_CANCELLED"

class LiveEvent(BaseModel):
    event_id: str = Field(default_factory=lambda: f"evt_{uuid.uuid4().hex[:10]}")
    session_id: str
    run_id: str
    sequence_number: int
    event_type: LiveEventType
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    payload: Dict[str, Any] = Field(default_factory=dict)
